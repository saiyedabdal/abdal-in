#!/usr/bin/env python3
"""Build the "Ask Abdal" knowledge base from PUBLIC sources only.

Sources: _src/knowledge/*.md (e.g. the LinkedIn profile) + the visible text of
the public pages listed below + field notes. Writes
netlify/functions/ask/knowledge.mjs. Nothing from /private, and nothing from
pages that are deliberately hidden (e.g. unpublished writings), goes in.

    python3 tools/build_knowledge.py
"""
import glob, html, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "netlify", "functions", "ask", "knowledge.mjs")

PAGES = [  # public, published pages only
    ("Home", "index.html"),
    ("Now", "now.html"),
    ("Day job / Entrepreneurship", "entrepreneurship.html"),
    ("My Story", "beyond-work.html"),
    ("The Studio (talks & videos)", "studio.html"),
    ("Books", "books.html"),
    ("Values", "quotes.html"),
    ("The UPSC years", "upsc.html"),
    ("Resources", "resources.html"),
    ("Dispatch (newsletter)", "dispatch.html"),
]


def text_of(path):
    s = open(os.path.join(ROOT, path), encoding="utf-8").read()
    s = re.sub(r"(?is)<(script|style|svg|noscript|header|nav)\b.*?</\1>", " ", s)
    s = re.sub(r'(?is)<footer class="foot".*?</footer>', " ", s)
    s = re.sub(r'(?is)<a class="topbar".*?</a>', " ", s)
    m = re.search(r"(?is)<main\b[^>]*>(.*)</main>", s)
    s = m.group(1) if m else s
    s = re.sub(r"(?i)<br\s*/?>|</(p|li|h[1-6]|div|section|tr)>", "\n", s)
    s = re.sub(r"<[^>]+>", " ", s)
    s = html.unescape(s)
    s = re.sub(r"[ \t ]+", " ", s)
    s = "\n".join(l.strip() for l in s.splitlines() if l.strip())
    return s


def main():
    parts = []
    for f in sorted(glob.glob(os.path.join(ROOT, "_src", "knowledge", "*.md"))):
        parts.append(open(f, encoding="utf-8").read().strip())
    for title, path in PAGES:
        if os.path.exists(os.path.join(ROOT, path)):
            parts.append(f"# abdal.in page: {title} (https://abdal.in/{path.replace('index.html', '')})\n"
                         + text_of(path))
    parts.append("# Other public places\n"
                 "- Poetry archive (119 Hindi/Urdu ghazals, shers and Sufi poems): https://abdal.in/poetry.html\n"
                 "- UPSC notes (free): https://abdal.in/upsc/notes/ and https://upscvision.org\n"
                 "- Ghazal blog: https://poeticcwhisperss.com\n"
                 "- Instagram: @saiyedabdal (personal), @practicalplaybook (mental models)\n"
                 "- X: @saiyedspeaks · YouTube: @SaiyedAbdal · Email: smahsanabdal@gmail.com\n"
                 "- Frido: https://myfrido.com")
    kb = "\n\n---\n\n".join(parts)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write(
        "// Generated by tools/build_knowledge.py from public sources. Do not hand-edit.\n"
        f"export default {json.dumps(kb, ensure_ascii=False)};\n")
    print(f"  knowledge: {len(kb):,} chars (~{len(kb)//4:,} tokens) -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
